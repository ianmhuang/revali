# gh stub: answers `pr list -R <repo> ...` from BACKFILL_REVIEW_FIXTURE, a JSON file mapping
# "<owner>/<name>" to a list of PRs or to {"fail": "<stderr text>"}.
GH_STUB = """\
import json, os, sys
argv = sys.argv[1:]
if argv[:2] != ["pr", "list"] or "-R" not in argv:
    sys.exit("stub: unexpected call %r" % (argv,))
if "--state" in argv and argv[argv.index("--state") + 1] != "merged":
    sys.exit("stub: expected --state merged")
with open(os.environ["BACKFILL_REVIEW_FIXTURE"], encoding="utf-8") as fh:
    data = json.load(fh)
answer = data.get(argv[argv.index("-R") + 1])
if answer is None:
    sys.exit("gh: repository not in fixture")
if isinstance(answer, dict):
    sys.exit(answer["fail"])
print(json.dumps(answer))
"""

