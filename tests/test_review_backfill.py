class Rerun(BackfillCase):
    """AC-3"""

    def test_an_archive_written_by_merge_survives(self):
        d = self.dest()
        os.makedirs(os.path.join(d, "logs"))
        # newline="": the fixture is read back with newline="" below; text mode would turn it
        # into CRLF on Windows and the assertion would blame the tool for the test's own file
        with open(os.path.join(d, "state.json"), "w", encoding="utf-8", newline="") as fh:
            fh.write('{"stage": "merged", "pr_number": 7}\n')
        with open(os.path.join(d, "logs", "revali.log"), "w", encoding="utf-8", newline="") as fh:
            fh.write("real\n")
        code, out, err = self.run_tool("me/proj")
        self.assertEqual(code, 0, err)
        self.assertEqual(files_under(d), ["logs/revali.log", "state.json"])
        state = read(os.path.join(d, "state.json"))
        self.assertEqual(state, '{"stage": "merged", "pr_number": 7}\n')
        lines = self.pr_lines(out, 7)
        self.assertEqual(len(lines), 1, out)
        self.assertIn("skipped", lines[0])
        self.assertTrue(os.path.isdir(self.dest("9-fix__plain")))  # the others still land

    def test_a_second_run_creates_nothing_and_exits_0(self):
        code, out, err = self.run_tool("me/proj")
        self.assertEqual(code, 0, err)
        before = {p: read(os.path.join(self.archive(), p)) for p in files_under(self.archive())}
        stamps = {p: os.path.getmtime(os.path.join(self.archive(), p)) for p in before}
        code, out, err = self.run_tool("me/proj")
        self.assertEqual(code, 0, err)
        after = {p: read(os.path.join(self.archive(), p)) for p in files_under(self.archive())}
        self.assertEqual(after, before)
        for p in before:
            self.assertEqual(os.path.getmtime(os.path.join(self.archive(), p)), stamps[p], p)
        for number in (7, 9):
            self.assertIn("skipped", "".join(self.pr_lines(out, number)), out)


