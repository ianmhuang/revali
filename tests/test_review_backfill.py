def pr(number, branch, body, comments=(), files=(), title=None):
    return {
        "number": number,
        "title": title or "PR %d title" % number,
        "headRefName": branch,
        "baseRefName": "main",
        "mergedAt": "2026-08-30T12:00:%02dZ" % number,
        "mergeCommit": {"oid": "c0ffee%02d" % number},
        "url": "https://example.invalid/me/proj/pull/%d" % number,
        "body": body,
        "comments": [{"author": {"login": "me"}, "body": c} for c in comments],
        "files": [{"path": p} for p in files],
    }


def read(path):
    with open(path, "r", encoding="utf-8", newline="") as fh:
        return fh.read()


def files_under(root):
    found = []
    for base, _dirs, names in os.walk(root):
        for name in names:
            found.append(os.path.relpath(os.path.join(base, name), root).replace("\\", "/"))
    return sorted(found)


class BackfillCase(RepoCase):
    with_remote = False
    with_branch = False

    def setUp(self):
        super().setUp()
        self.stub = os.path.join(self.tmp, "gh_review_stub.py")
        with open(self.stub, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(GH_STUB)
        self.fixture = os.path.join(self.tmp, "review prs.json")
        os.environ["REVALI_GH_CMD"] = "%s %s" % (_quote(sys.executable), _quote(self.stub))
        os.environ["BACKFILL_REVIEW_FIXTURE"] = self.fixture
        self.prs({"me/proj": self.default_prs()})
        self.history(
            [
                {"repo": "me/proj", "branch": "feature/mul", "stage": "review", "rounds": 1},
                {"repo": "me/proj", "branch": "fix/plain", "stage": "merged", "rounds": 1},
                {"repo": "other/proj", "branch": "feature/mul", "stage": "merged", "rounds": 9},
                {"repo": "me/proj", "branch": "feature/mul", "stage": "merged", "rounds": 2},
            ]
        )

    def default_prs(self):
        return [
            pr(
                7,
                "feature/mul",
                BODY_CRLF,
                [REVIEW_1, VALIDATION_1, CHATTER, REVIEW_2_CRLF, WITHHELD, VALIDATION_2],
                ["src/calc.py", "tests/test_review_mul.py", "tests/test_calc.py"],
                title="Add mul",
            ),
            pr(8, "chore/bump", "Bump the version.\r\n"),
            pr(9, "fix/plain", BODY_PLAIN),
        ]

    def prs(self, data):
        with open(self.fixture, "w", encoding="utf-8") as fh:
            json.dump(data, fh)

    def history(self, rows):
        with open(os.path.join(self.home, "history.jsonl"), "w", encoding="utf-8") as fh:
            fh.write("".join(json.dumps(r) + "\n" for r in rows))

    def user_config(self, text):
        with open(os.path.join(self.home, "config.toml"), "w", encoding="utf-8") as fh:
            fh.write(text)

    def run_tool(self, *args, env=None):
        res = subprocess.run(
            [sys.executable, SCRIPT] + list(args),
            capture_output=True,
            text=True,
            encoding="utf-8",
            cwd=self.tmp,
            env=env,
        )
        return res.returncode, res.stdout, res.stderr

    def archive(self):
        return os.path.join(self.home, "archive")

    def dest(self, name="7-feature__mul", root=None):
        return os.path.join(root or self.archive(), "me__proj", name)

    def pr_lines(self, out, number):
        return [ln for ln in out.splitlines() if "#%d" % number in ln]


class Layout(BackfillCase):
    """AC-1"""

    def test_one_directory_per_revali_pr_under_the_default_root(self):
        code, out, err = self.run_tool("me/proj")
        self.assertEqual(code, 0, err)
        self.assertNotIn("Traceback", err)
        self.assertTrue(os.path.isdir(self.dest()), out)
        self.assertTrue(os.path.isdir(self.dest("9-fix__plain")), out)
        self.assertEqual(sorted(os.listdir(self.dest(""))), ["7-feature__mul", "9-fix__plain"])
        self.assertEqual(os.listdir(self.archive()), ["me__proj"])
