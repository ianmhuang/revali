class Dependencies(unittest.TestCase):
    """AC-6: the import list; the README and docs wording is documentation."""

    def test_the_script_imports_only_stdlib_and_revali(self):
        tree = ast.parse(read(SCRIPT))
        names = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                names.update(alias.name.split(".")[0] for alias in node.names)
            elif isinstance(node, ast.ImportFrom):
                names.add((node.module or "").split(".")[0])
        foreign = sorted(n for n in names if n != "revali" and n not in sys.stdlib_module_names)
        self.assertEqual(foreign, [])


