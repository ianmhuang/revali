BODY_CRLF = "\r\n".join(CHANGE_LINES + STATUS_LINES) + "\r\n"
BODY_PLAIN = "---\ntitle: Plain fix\nkind: fix\nauthor_model: m\n---\n\n## Request\nfix it\n"

